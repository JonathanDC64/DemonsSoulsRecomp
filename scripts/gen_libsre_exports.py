#!/usr/bin/env python3
"""Generate the port-side libsre LLE glue: export table, import bridge, loader.

WHY
---
ps3recomp's HLE dispatcher ALREADY prefers a loaded firmware PRX over its own
stub: ps3_hle_call() calls prx_resolve_export(nid) and, on a hit, dispatches into
the real lifted Sony code. That bridge sat dormant because nothing ever called
prx_load_module(). This generates the missing wiring.

Inputs (from scripts/build_libsre.sh):
  work/libsre/libsre_exports.json   NID -> absolute vaddr (base already applied)
  work/libsre/libsre_imports.json   NID -> import stub slot
  work/libsre/libsre_image.bin      the relocated image
  work/libsre/lifted/ppu_recomp.c   the lifted code (libsre_function_table[])

Output: port/gen/libsre_glue.c -- GITIGNORED (firmware-derived), see docs/05-legal.md.
--src, --out and --runtime-image move them (setup keeps them in its data folder).

GATING: the loader only runs when LIBSRE_LLE=1. Unset, prx_resolve_export keeps
returning 0 and every SPURS call takes the existing HLE path, so the default
build is behaviourally identical and reverting is free.
"""
import argparse
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "work", "libsre")
OUT = os.path.join(ROOT, "port", "gen", "libsre_glue.c")
MODULE_PREFIX = "@module/"   # --runtime-image: from the game module's folder (setup's lift.py)

NL = chr(92) + "n"          # a literal backslash-n for the emitted C


def decode_stub_entry(img, base, slot):
    """Recover the import pointer-table entry a stub slot loads from.

    Each import stub is:
        li   r12, lo
        oris r12, r12, hi
        lwz  r12, disp(r12)     <- the pointer-table entry
        lwz  r0, 0(r12) ; lwz r2, 4(r12) ; mtctr r0 ; bctr
    so the entry holds a POINTER TO AN OPD. Decode the three instructions rather
    than assuming a table layout.
    """
    o = slot - base
    w = [struct.unpack_from(">I", img, o + i * 4)[0] for i in range(3)]
    if ((w[0] & 0xFFFF0000) != 0x39800000 or
            (w[1] & 0xFFFF0000) != 0x658C0000 or
            (w[2] & 0xFFFF0000) != 0x818C0000):
        return None
    lo = w[0] & 0xFFFF
    r12 = lo - 0x10000 if lo & 0x8000 else lo
    r12 |= (w[1] & 0xFFFF) << 16
    dsp = w[2] & 0xFFFF
    dsp = dsp - 0x10000 if dsp & 0x8000 else dsp
    return (r12 + dsp) & 0xFFFFFFFF


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the port-side libsre LLE glue.")
    ap.add_argument("--src", default=SRC, help="build_libsre's output (default work/libsre)")
    ap.add_argument("--out", default=OUT, help="the glue file (default port/gen/libsre_glue.c)")
    ap.add_argument("--runtime-image", default="work/libsre/libsre_image.bin", metavar="PATH",
                    help="where the game loads the image from at run time (default work/libsre/libsre_image.bin, "
                         "from the working folder); @module/<path> is <path> from the folder of the game module "
                         "(PS3_GAME_MODULE), as setup builds it. PS3_LIBSRE_IMAGE overrides it at run time")
    args = ap.parse_args(argv)
    src, out = args.src, args.out
    rimg = args.runtime_image.replace(chr(92), "/").replace('"', "")
    ej = os.path.join(src, "libsre_exports.json")
    if not os.path.exists(ej):
        print("[libsre] %s not found -- skipping (LLE glue not built)" % ej)
        return 0

    d = json.load(open(ej))
    base = int(str(d["base"]), 16)
    toc  = int(str(d["toc"]), 16)

    exports = []
    for lib, fns in d["exports"].items():
        for nid, ea in fns.items():
            exports.append((int(str(nid), 16), int(str(ea), 16) - base, lib))
    exports.sort(key=lambda r: r[0])

    img = open(os.path.join(src, "libsre_image.bin"), "rb").read()
    imports = []
    ij = os.path.join(src, "libsre_imports.json")
    if os.path.exists(ij):
        for lib, fns in json.load(open(ij)).items():
            for nid, slot in fns.items():
                e = decode_stub_entry(img, base, int(str(slot), 16))
                if e is not None:
                    imports.append((int(str(nid), 16), e, lib))
    imports.sort(key=lambda r: r[1])

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    w = []
    a = w.append
    a("/* GENERATED by scripts/gen_libsre_exports.py -- do not edit, do not commit.")
    a(" *")
    a(" * FIRMWARE-DERIVED (libsre export/import tables). port/gen/ is gitignored;")
    a(" * see docs/05-legal.md. Regenerate with scripts/build_libsre.sh.")
    a(" *")
    a(" * Wires the REAL lifted Sony SPURS kernel into the dispatcher. ps3_hle_call()")
    a(" * already prefers prx_resolve_export(nid) over its HLE stub; loading the module")
    a(" * is what makes that bridge live for these %d exports." % len(exports))
    a(" *")
    a(" * GATED: only loads when LIBSRE_LLE=1. Unset -> nothing is registered,")
    a(" * prx_resolve_export returns 0, and every call takes the existing HLE path.")
    a(" */")
    a("#include <stdio.h>")
    a("#include <stdlib.h>")
    a("#include <stdint.h>")
    a("#include <string.h>")
    a('#include "prx_loader.h"')
    a("")
    a("#define LIBSRE_BASE 0x%08Xu" % base)
    a("#define LIBSRE_TOC  0x%08Xu" % toc)
    a("")
    a("/* Binary-compatible with the lifter's func_entry (see prx_loader.h). */")
    a("extern const prx_func_entry libsre_function_table[];")
    a("extern const uint64_t       libsre_function_table_count;")
    a("")
    a("static const prx_export k_libsre_exports[] = {")
    for nid, v, lib in exports:
        a("    { 0x%08Xu, 0x%08Xu },   /* %s */" % (nid, v, lib))
    a("};")
    a("")
    a("/* ---- libsre's own imports (FIRMWARE_LLE.md step 4.2) ---------------------")
    a(" * Each pointer-table entry must point at an OPD whose func is a guest address")
    a(" * our dispatcher can resolve. We synthesise one OPD + one guest address per")
    a(" * import and register a trampoline forwarding to our HLE, so libsre's calls to")
    a(" * sysPrxForUser/cellLibprof land in the same handlers the game would use.")
    a(" * Unpatched, the module branches into unrelocated stub code -- observed as")
    a(" * `unresolved indirect call -> 0x39800000` (a bare `li r12,0` word).")
    a(" */")
    a("extern void ps3_hle_call(uint32_t nid, void* ctx);")
    a("extern void vm_write32(unsigned long long ea, unsigned int v);")
    a("extern void ppu_register_function(uint64_t addr, void (*fn)(void*));")
    a("extern const void* g_extra_symtab;")
    a("extern uint64_t    g_extra_symtab_count;")
    a("")
    a("#define LIBSRE_BRIDGE_BASE 0x30040000u   /* past the image (ends ~0x30032340) */")
    a("#define LIBSRE_OPD(i)   (LIBSRE_BRIDGE_BASE + (unsigned)(i) * 8u)")
    a("#define LIBSRE_TRAMP(i) (LIBSRE_BRIDGE_BASE + 0x800u + (unsigned)(i) * 4u)")
    a("#define LIBSRE_IMPORT_COUNT %du" % len(imports))
    a("")
    a("typedef struct { uint32_t nid; uint32_t entry; } libsre_import;")
    a("static const libsre_import k_libsre_imports[] = {")
    for nid, e, lib in imports:
        a("    { 0x%08Xu, 0x%08Xu },   /* %s */" % (nid, e, lib))
    a("};")
    a("")
    for i, (nid, e, lib) in enumerate(imports):
        a("static void libsre_tramp_%d(void* c) { ps3_hle_call(0x%08Xu, c); }" % (i, nid))
    a("")
    a("static void (*const k_libsre_tramps[])(void*) = {")
    for i in range(len(imports)):
        a("    libsre_tramp_%d," % i)
    a("};")
    a("")
    a("/* Our runtime's guest-addr -> host-fn registrar, adapted to prx_register_fn. */")
    a("static void libsre_reg(uint32_t guest_addr, void (*host)(void*))")
    a("{")
    a("    ppu_register_function((uint64_t)guest_addr, host);")
    a("}")
    a("")
    a("/* The image's path: PS3_LIBSRE_IMAGE when it is set, else the one this glue was")
    a(" * generated with. For setup's build that one is given from the folder of the")
    a(" * game module (PS3_GAME_MODULE), so the module holds no folder of the PC it was")
    a(" * built on. (Plain loops: a freestanding module has no strrchr or snprintf.) */")
    a("static const char* libsre_image_path(char* buf, size_t cap)")
    a("{")
    a('    const char* given = getenv("PS3_LIBSRE_IMAGE");')
    a("    if (given && given[0]) return given;")
    if rimg.startswith(MODULE_PREFIX):
        a('    static const char rest[] = "%s";' % rimg[len(MODULE_PREFIX):])
        a('    const char* mod = getenv("PS3_GAME_MODULE");')
        a("    if (!mod || !mod[0]) return rest;")
        a("    size_t dir = 0;")
        a("    for (size_t i = 0; mod[i]; ++i)")
        a("        if (mod[i] == '/' || mod[i] == 92) dir = i + 1;")
        a("    if (dir + sizeof rest > cap) return rest;")
        a("    memcpy(buf, mod, dir);")
        a("    memcpy(buf + dir, rest, sizeof rest);")
        a("    return buf;")
    else:
        a("    (void)buf; (void)cap;")
        a('    return "%s";' % rimg)
    a("}")
    a("")
    a("/* Strong override of ps3recomp's weak ps3_load_prx_modules() hook: boot_main")
    a(" * calls it after the lifted function table is registered and vm_base is live,")
    a(" * and before any guest code runs -- exactly what a PRX load needs. */")
    a("void ps3_load_prx_modules(void)")
    a("{")
    a('    const char* e = getenv("LIBSRE_LLE");')
    a("    if (!e || e[0] == '0') return;")
    a("")
    a("    char path_buf[1024];")
    a("    const char* path = libsre_image_path(path_buf, sizeof path_buf);")
    a("    uint32_t sz = 0;")
    a("    uint8_t* img = prx_image_load_file(path, &sz);")
    a("    if (!img) {")
    a('        fprintf(stderr, "[libsre] LIBSRE_LLE set but %s could not be read -- staying on HLE%c", path, 10);')
    a("        return;")
    a("    }")
    a("")
    a("    prx_module m;")
    a('    m.name         = "libsre";')
    a("    m.base         = LIBSRE_BASE;")
    a("    m.image        = img;")
    a("    m.image_size   = sz;")
    a("    m.funcs        = libsre_function_table;")
    a("    m.func_count   = libsre_function_table_count;")
    a("    m.exports      = k_libsre_exports;")
    a("    m.export_count = (uint32_t)(sizeof k_libsre_exports / sizeof k_libsre_exports[0]);")
    a("")
    a("    prx_load_result r = prx_load_module(&m, libsre_reg);")
    a("")
    a("    /* Let the host-stack symboliser resolve libsre frames. Without this a")
    a("     * frame inside libsre resolves to whichever GAME function sits below it")
    a("     * in host memory -- a plausible but wrong guest address. */")
    a("    g_extra_symtab       = (const void*)libsre_function_table;")
    a("    g_extra_symtab_count = libsre_function_table_count;")
    a("")
    a("    /* Patch libsre's own import table AFTER the load (which copies the")
    a("     * unpatched image into guest RAM): entry -> OPD{trampoline, 0}. */")
    a("    for (unsigned i = 0; i < LIBSRE_IMPORT_COUNT; i++) {")
    a("        uint32_t opd = LIBSRE_OPD(i), tr = LIBSRE_TRAMP(i);")
    a("        vm_write32(opd + 0, tr);   /* OPD.func */")
    a("        /* OPD.toc MUST be libsre's own TOC. The import stub does")
    a("         *     std r2,0x28(r1) ; lwz r0,0(r12) ; lwz r2,4(r12) ; bctr")
    a("         * so whatever sits here becomes r2 for the rest of libsre. A zero")
    a("         * here left r2 = 0, and every TOC-relative load then read from a")
    a("         * bogus address and returned 0 -- which is exactly how libsre came")
    a("         * to pass entry=0 and prio=0 to sys_ppu_thread_create while its")
    a("         * register-computed arguments (arg/stack/flags/name) were correct. */")
    a("        vm_write32(opd + 4, LIBSRE_TOC);   /* OPD.toc */")
    a("        vm_write32(k_libsre_imports[i].entry, opd);")
    a("        ppu_register_function((uint64_t)tr, k_libsre_tramps[i]);")
    a("    }")
    a("")
    a('    fprintf(stderr, "[libsre] LLE load: ok=%d base=0x%08X image=%u funcs=%u"')
    a('                    " exports=%u imports_patched=%u%c",')
    a("            r.ok, r.base, r.image_size, r.funcs_registered,")
    a("            m.export_count, LIBSRE_IMPORT_COUNT, 10);")
    a("}")
    a("")

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(w))

    print("[libsre] wrote %s" % out)
    print("[libsre]   base 0x%08X, %d exports, %d import stubs bridged"
          % (base, len(exports), len(imports)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
