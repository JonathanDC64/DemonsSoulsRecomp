#!/usr/bin/env python3
"""Generate the SPURS taskset-policy blob TU for des_boot.

WHY
---
`ps3recomp/runtime/spu/spurs_policy.c` can run the REAL Sony SPURS taskset policy
module (`spurs_run_taskset_policy_probe`, behind `LBP_REAL_POLICY=1`) as an A/B
oracle: it runs the authentic policy far enough to build the SpursTasksetContext at
LS 0x2700, then diffs that against our C reimplementation
(`spurs_pm_build_context()` in `libs/spurs/spurs_pm.c`) and dumps the taskset task
bitsets. That is the sharpest available tool for the current gate -- a two-sided
deadlock where the PPU waits in `cellSpursEventFlagWait` while an SPU task sits in
`WAIT_SIGNAL`.

It needs two things a port must supply, which default to a zero-size weak stub
(`runtime/spu/spurs_policy_blob_weak.c`, `spu_tsp_weak.c`) -- and with size 0 the
probe bails out at spurs_policy.c:484 and does nothing:

  * `g_taskset_policy_bytes` / `g_taskset_policy_size` -- the module's RAW bytes,
    memcpy'd to LS 0xA00 (its code AND the data tables it reads via `lqr`).
  * `tsp_spu_func_00000A00` + `tsp_spu_recomp_register()` -- the lifted policy,
    already present at `ps3recomp/fw_spu/spu_libsre/taskset_policy_lifted/`,
    registered under image id 100 (its own indirect-branch table).

EXTENT (verified, not guessed)
------------------------------
The module lives at libsre vaddr 0x23680, which is where LS 0xA00 maps. libsre.prx
PT_LOAD[0] puts vaddr 0 at file offset 0x100, so the file offset is 0x23780. The
first word there is 0x4306DC02 = `ila $2, 0x20DB8`, which matches the first
instruction of the lifted `tsp_spu_func_00000A00` exactly -- that is the check that
the base is right, and this script re-asserts it every run.

The module ends at LS 0x2840: its data tables run to 0x27B0-0x2840 (per
spurs_policy.c), the highest lifted function is at 0x2820, and the image is
zero-padded from 0x2840 until a DIFFERENT policy module starts at LS 0x2880. So the
blob is LS 0xA00..0x2840 = 0x1E40 bytes.

LEGAL
-----
The output is FIRMWARE-DERIVED and must never be committed: it is written to
`port/gen/` which is gitignored, and is regenerated from the user's own
`fw_spu/libsre.prx`. See docs/05-legal.md. If libsre.prx is absent this script exits
0 without writing, so a tree without firmware still configures and builds -- the
weak stub then links and the probe stays inert.
"""
import os
import struct
import sys

ROOT     = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRX      = os.path.join(ROOT, "ps3recomp", "fw_spu", "libsre.prx")
OUT_DIR  = os.path.join(ROOT, "port", "gen")
OUT_C    = os.path.join(OUT_DIR, "taskset_policy_blob.c")

POLICY_VADDR = 0x23680   # libsre vaddr where the taskset policy module begins
LS_BASE      = 0xA00     # local-store address it is loaded at
LS_END       = 0x2840    # end of its data tables (zero padding follows)
BLOB_LEN     = LS_END - LS_BASE          # 0x1E40
FIRST_WORD   = 0x4306DC02                # ila $2, 0x20DB8 -- the base check


def vaddr_to_offset(buf: bytes, vaddr: int) -> int:
    """Map a PRX vaddr to a file offset via the ELF64-BE program headers."""
    e_phoff = struct.unpack_from(">Q", buf, 0x20)[0]
    e_phentsize, e_phnum = struct.unpack_from(">HH", buf, 0x36)
    for i in range(e_phnum):
        o = e_phoff + i * e_phentsize
        p_type = struct.unpack_from(">I", buf, o)[0]
        if p_type != 1:                                   # PT_LOAD only
            continue
        p_offset, p_vaddr, _p_paddr, p_filesz = struct.unpack_from(">QQQQ", buf, o + 8)
        if p_vaddr <= vaddr < p_vaddr + p_filesz:
            return p_offset + (vaddr - p_vaddr)
    raise SystemExit(f"vaddr 0x{vaddr:X} is not inside any PT_LOAD segment of libsre.prx")


def main() -> int:
    if not os.path.exists(PRX):
        print(f"[taskset-policy] {PRX} not found -- skipping "
              f"(the zero-size weak stub will link; LBP_REAL_POLICY stays inert)")
        return 0

    buf = open(PRX, "rb").read()
    off = vaddr_to_offset(buf, POLICY_VADDR)
    if off + BLOB_LEN > len(buf):
        raise SystemExit("libsre.prx is truncated: policy module runs past EOF")

    first = struct.unpack_from(">I", buf, off)[0]
    if first != FIRST_WORD:
        raise SystemExit(
            f"policy base check FAILED: expected 0x{FIRST_WORD:08X} "
            f"(ila $2,0x20DB8) at vaddr 0x{POLICY_VADDR:X} (file 0x{off:X}), got 0x{first:08X}.\n"
            f"This libsre.prx has a different layout -- re-derive POLICY_VADDR before trusting the blob.")

    blob = buf[off:off + BLOB_LEN]
    os.makedirs(OUT_DIR, exist_ok=True)

    with open(OUT_C, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "/* GENERATED by scripts/gen_taskset_policy_blob.py -- do not edit, do not commit.\n"
            " *\n"
            " * FIRMWARE-DERIVED: raw bytes of the SPURS taskset policy module, extracted from\n"
            f" * the local libsre.prx at vaddr 0x{POLICY_VADDR:X} (file offset 0x{off:X}),\n"
            f" * covering local store 0x{LS_BASE:X}..0x{LS_END:X} ({BLOB_LEN} bytes).\n"
            " *\n"
            " * Consumed by ps3recomp/runtime/spu/spurs_policy.c, which memcpy's it to LS 0xA00\n"
            " * and runs the authentic policy as an A/B oracle against our C reimplementation\n"
            " * (spurs_pm_build_context). Overrides the zero-size weak stub in\n"
            " * runtime/spu/spurs_policy_blob_weak.c.\n"
            " *\n"
            " * Also registers the lifted policy (fw_spu/spu_libsre/taskset_policy_lifted) under\n"
            " * image id 100 -- its own indirect-branch table, which spurs_policy.c expects.\n"
            " */\n\n")
        f.write(f"const unsigned char g_taskset_policy_bytes[{BLOB_LEN}] = {{\n")
        for i in range(0, BLOB_LEN, 12):
            row = ", ".join(f"0x{b:02X}" for b in blob[i:i + 12])
            f.write(f"    {row},\n")
        f.write("};\n")
        f.write(f"const unsigned g_taskset_policy_size = {BLOB_LEN}u;\n\n")
        f.write(
            "/* Register the lifted policy's 130 functions under image id 100 at startup,\n"
            " * mirroring work_spu/_gen/spu_workloads.cpp. spurs_policy.c sets\n"
            " * ctx->image_id = 100 before entering tsp_spu_func_00000A00, so its indirect\n"
            " * branches resolve against this table and nothing else. */\n"
            "extern void spu_begin_image(int image_id);\n"
            "extern void tsp_spu_recomp_register(void);\n\n"
            "__attribute__((constructor))\n"
            "static void des_taskset_policy_autoreg(void)\n"
            "{\n"
            "    spu_begin_image(100);\n"
            "    tsp_spu_recomp_register();\n"
            "    spu_begin_image(0);\n"
            "}\n")

    print(f"[taskset-policy] wrote {OUT_C}")
    print(f"[taskset-policy]   libsre vaddr 0x{POLICY_VADDR:X} -> file 0x{off:X}, "
          f"LS 0x{LS_BASE:X}..0x{LS_END:X}, {BLOB_LEN} bytes, base check OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
